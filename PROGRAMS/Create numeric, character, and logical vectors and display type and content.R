# Create a numeric vector
numeric_vector <- c(10, 20, 30, 40, 50)

# Create a character vector
character_vector <- c("Apple", "Banana", "Cherry")

# Create a logical vector
logical_vector <- c(TRUE, FALSE, TRUE, FALSE)

# Display numeric vector and its type
print("Numeric Vector:")
print(numeric_vector)
print(typeof(numeric_vector))

# Display character vector and its type
print("Character Vector:")
print(character_vector)
print(typeof(character_vector))

# Display logical vector and its type
print("Logical Vector:")
print(logical_vector)
print(typeof(logical_vector))